#!/usr/bin/env python3
"""
Real Binance Spot Testnet Execution Harness.
Executes live requests against https://testnet.binance.vision using HMAC-SHA256 testnet credentials.

Flow verified:
1. Places OCO order (POST /api/v3/order/oco).
2. Attempts market SELL while OCO is active (capturing -2010 rejection).
3. Cancels OCO order list (DELETE /api/v3/orderList).
4. Verifies base asset unlocked (GET /api/v3/account).
5. Executes market SELL order (POST /api/v3/order).

Prerequisite:
Create .env.testnet or supply environment variables:
BINANCE_TESTNET_API_KEY=<your-key>
BINANCE_TESTNET_API_SECRET=<your-secret>
(Generated by logging in with GitHub at https://testnet.binance.vision)
"""

import os
import sys
import json
import time
import hmac
import hashlib
import urllib.request
import urllib.parse
import urllib.error
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

TESTNET_URL = "https://testnet.binance.vision"
SERVER_TIME_OFFSET = 0

def load_testnet_env():
    env_file = ROOT / ".env.testnet"
    if env_file.exists():
        for line in env_file.read_text("utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                os.environ.setdefault(k.strip(), v.strip())

    key = os.getenv("BINANCE_TESTNET_API_KEY") or os.getenv("BINANCE_API_KEY")
    secret = os.getenv("BINANCE_TESTNET_API_SECRET") or os.getenv("BINANCE_API_SECRET")
    return key, secret


def sync_server_time():
    global SERVER_TIME_OFFSET
    try:
        with urllib.request.urlopen(f"{TESTNET_URL}/api/v3/time", timeout=10) as r:
            server_time = json.loads(r.read())["serverTime"]
            SERVER_TIME_OFFSET = server_time - int(time.time() * 1000)
    except Exception as e:
        SERVER_TIME_OFFSET = 0


def signed_request(key: str, secret: str, method: str, endpoint: str, params: dict = None):
    params = dict(params or {})
    params["recvWindow"] = 10000
    params["timestamp"] = int(time.time() * 1000) + SERVER_TIME_OFFSET - 500
    query_str = urllib.parse.urlencode(params)
    sig = hmac.new(secret.encode("utf-8"), query_str.encode("utf-8"), hashlib.sha256).hexdigest()
    url = f"{TESTNET_URL}{endpoint}?{query_str}&signature={sig}"
    
    headers = {
        "X-MBX-APIKEY": key,
        "User-Agent": "BinanceTestnetClient/1.0"
    }

    req = urllib.request.Request(url, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            return resp.status, json.loads(resp.read().decode())
    except urllib.error.HTTPError as err:
        try:
            err_body = json.loads(err.read().decode())
        except Exception:
            err_body = {"error": str(err)}
        return err.code, err_body


def main():
    print("=" * 80)
    print("   BINANCE SPOT TESTNET REAL EXECUTION HARNESS")
    print(f"   Target Endpoint: {TESTNET_URL}")
    print("=" * 80)

    key, secret = load_testnet_env()

    if not key or not secret or "mock" in key.lower():
        print("\n[SKIPPED / BLOCKED] Real testnet credentials NOT detected.")
        print("Binance Spot Testnet requires manual authentication via GitHub OAuth at:")
        print("  --> https://testnet.binance.vision")
        print("\nTo execute this real integration harness:")
        print("1. Log in to https://testnet.binance.vision with your GitHub account.")
        print("2. Click 'Generate HMAC_SHA256 Key' and copy API Key and Secret Key.")
        print("3. Create file .env.testnet with:")
        print("     BINANCE_TESTNET_API_KEY=<your_api_key>")
        print("     BINANCE_TESTNET_API_SECRET=<your_api_secret>")
        print("4. Re-run this script to execute live orders on the Binance Spot Testnet.")
        print("\nStatus: SKIPPED (Missing Testnet Credentials)")
        sys.exit(2)

    sync_server_time()

    # Cancel any pre-existing open orders on BTCUSDT to ensure clean initial slate
    signed_request(key, secret, "DELETE", "/api/v3/openOrders", {"symbol": "BTCUSDT"})

    print("\n[1] Querying Initial Account Information...")
    status, acct = signed_request(key, secret, "GET", "/api/v3/account")
    print(f"GET /api/v3/account -> HTTP {status}")
    if status != 200:
        print("[!] Failed to connect to testnet with provided credentials.")
        sys.exit(1)

    btc_entry = next((b for b in acct.get("balances", []) if b["asset"] == "BTC"), None)
    assert btc_entry is not None, "BTC balance not found in testnet account"
    initial_free_btc = float(btc_entry["free"])
    print(f"Initial BTC Balance: free={initial_free_btc}, locked={btc_entry['locked']}")

    symbol = "BTCUSDT"
    oco_qty = "0.001"
    
    # Fetch current price to place valid bracket orders
    with urllib.request.urlopen(f"{TESTNET_URL}/api/v3/ticker/price?symbol={symbol}", timeout=10) as r:
        curr_price = float(json.loads(r.read())["price"])
    target_price = f"{round(curr_price * 1.15, 2):.2f}"
    stop_price = f"{round(curr_price * 0.90, 2):.2f}"
    stop_limit_price = f"{round(curr_price * 0.89, 2):.2f}"
    print(f"Current {symbol} Price: {curr_price:.2f} (Target: {target_price}, Stop: {stop_price}, StopLimit: {stop_limit_price})")

    # 1. Place OCO order
    print(f"\n[2] Placing OCO Order for {oco_qty} {symbol}...")
    oco_params = {
        "symbol": symbol,
        "side": "SELL",
        "quantity": oco_qty,
        "price": target_price,
        "stopPrice": stop_price,
        "stopLimitPrice": stop_limit_price,
        "stopLimitTimeInForce": "GTC"
    }
    status, oco_res = signed_request(key, secret, "POST", "/api/v3/order/oco", oco_params)
    print(f"POST /api/v3/order/oco -> HTTP {status}")
    print(json.dumps(oco_res, indent=2))

    if status != 200:
        print(f"[!] Could not place testnet OCO order. Response: {oco_res}")
        sys.exit(1)

    order_list_id = oco_res.get("orderListId")

    # 2. Market sell while OCO is active (Assert -2010 rejection)
    # Since 0.001 BTC is locked in OCO, attempting to sell initial_free_btc requires the locked portion and fails.
    attempt_sell_qty = f"{initial_free_btc:.5f}"
    print(f"\n[3] Attempting Market SELL for {attempt_sell_qty} {symbol} while OCO is active (free={initial_free_btc - float(oco_qty):.5f}, locked={oco_qty})...")
    rej_sell_params = {
        "symbol": symbol,
        "side": "SELL",
        "type": "MARKET",
        "quantity": attempt_sell_qty
    }
    status, rej_res = signed_request(key, secret, "POST", "/api/v3/order", rej_sell_params)
    print(f"POST /api/v3/order (Market SELL while OCO active) -> HTTP {status}")
    print(json.dumps(rej_res, indent=2))
    assert rej_res.get("code") == -2010, f"Expected code == -2010 (Insufficient Balance rejection), got: {rej_res}"
    print("--> Successfully verified rejection (code == -2010) while OCO holds lock on base asset.")

    # 3. Cancel OCO order list
    print(f"\n[4] Canceling OCO Order List #{order_list_id}...")
    status, cancel_res = signed_request(key, secret, "DELETE", "/api/v3/orderList", {"symbol": symbol, "orderListId": order_list_id})
    print(f"DELETE /api/v3/orderList -> HTTP {status}")
    print(json.dumps(cancel_res, indent=2))
    assert status == 200, f"Expected DELETE to return HTTP 200, got: {status}"
    assert cancel_res.get("listOrderStatus") == "ALL_DONE", f"Expected listOrderStatus == 'ALL_DONE', got: {cancel_res.get('listOrderStatus')}"

    # 4. Check account balance unlocked
    print("\n[5] Checking Account Balances after OCO cancellation...")
    status, post_cancel_acct = signed_request(key, secret, "GET", "/api/v3/account")
    print(f"GET /api/v3/account -> HTTP {status}")
    btc_bal = [b for b in post_cancel_acct.get("balances", []) if b["asset"] == "BTC"]
    print(json.dumps(btc_bal, indent=2))
    unlocked_free_btc = float(btc_bal[0]["free"])
    assert unlocked_free_btc >= initial_free_btc - 0.0001, f"Expected free BTC to unlock, got: {unlocked_free_btc}"

    # 5. Market SELL unlocked balance
    print(f"\n[6] Executing Market SELL for {oco_qty} {symbol} after unlock...")
    final_sell_params = {
        "symbol": symbol,
        "side": "SELL",
        "type": "MARKET",
        "quantity": oco_qty
    }
    status, fill_res = signed_request(key, secret, "POST", "/api/v3/order", final_sell_params)
    print(f"POST /api/v3/order -> HTTP {status}")
    print(json.dumps(fill_res, indent=2))
    assert status == 200, f"Expected market sell to succeed, got: {status}"
    assert fill_res.get("status") == "FILLED", f"Expected FILLED status, got: {fill_res.get('status')}"
    print("\n--> Real Testnet run finished successfully with all assertions passed.")


if __name__ == "__main__":
    main()
